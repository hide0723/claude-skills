# 職能ごとの帯色（上位ほど濃い）
BANDS = {
    "EP": "1F3864",
    "P": "2E5597",
    "D・SD": "4472C4",
    "M・SM": "8EA9DB",
    "SS": "B4C6E7",
    "S": "D9E2F3",
    "T1": "F2F2F2",
    "―": "FFFFFF",
}
WHITE_TEXT = {"EP", "P", "D・SD"}

FONT = "Yu Gothic"
thin = Side(style="thin", color="8C8C8C")
BORDER = Border(left=thin, right=thin, top=thin, bottom=thin)


def main() -> None:
    wb = Workbook()
    ws = wb.active
    ws.title = "期待職能"

    ncols = len(HEADERS)
    last_col = get_column_letter(ncols)

    # タイトル行
    ws.merge_cells(f"A1:{last_col}1")
    t = ws["A1"]
    t.value = f"期待職能　税理士法人福田会計（{VERSION}）"
    t.font = Font(name=FONT, size=16, bold=True)
    t.alignment = Alignment(horizontal="center", vertical="center")
    ws.row_dimensions[1].height = 28

    # ヘッダー行
    for i, (label, width) in enumerate(HEADERS, start=1):
        c = ws.cell(row=2, column=i, value=label)
        c.font = Font(name=FONT, size=9, bold=True, color="FFFFFF")
        c.fill = PatternFill("solid", fgColor="404040")
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        c.border = BORDER
        ws.column_dimensions[get_column_letter(i)].width = width
    ws.row_dimensions[2].height = 34

    # 本体
    for r, row in enumerate(ROWS, start=3):
        band = BANDS[row[0]]
        for i, val in enumerate(row, start=1):
            c = ws.cell(row=r, column=i, value=val)
            c.border = BORDER
            if i <= 5:  # 記号〜主な役割は帯色
                c.fill = PatternFill("solid", fgColor=band)
                color = "FFFFFF" if row[0] in WHITE_TEXT else "000000"
                c.font = Font(name=FONT, size=10, bold=(i <= 2), color=color)
                c.alignment = Alignment(
                    horizontal="center", vertical="center", wrap_text=True
                )
            else:
                c.font = Font(name=FONT, size=9)
                c.alignment = Alignment(
                    horizontal="left", vertical="top", wrap_text=True
                )
        # 行の高さは行数に応じて（1行あたり約13pt）
        lines = max(str(v).count("\n") + 1 for v in row)
        ws.row_dimensions[r].height = max(58, lines * 13.5)

    # 注記
    note_start = len(ROWS) + 4
    for j, note in enumerate(NOTES):
        r = note_start + j
        ws.merge_cells(f"A{r}:{last_col}{r}")
        c = ws.cell(row=r, column=1, value=note)
        c.font = Font(name=FONT, size=8)
        c.alignment = Alignment(horizontal="left", vertical="center")
        ws.row_dimensions[r].height = 14

    # 印刷設定（A3横・1ページ幅に収める）
    ws.page_setup.orientation = "landscape"
    ws.page_setup.paperSize = 8  # A3
    ws.page_setup.fitToWidth = 1
    ws.page_setup.fitToHeight = 0
    ws.sheet_properties.pageSetUpPr.fitToPage = True
    ws.page_margins = PageMargins(
        left=0.3, right=0.3, top=0.4, bottom=0.4, header=0.2, footer=0.2
    )
    ws.print_title_rows = "1:2"
    ws.freeze_panes = "F3"

    wb.save(OUT)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
